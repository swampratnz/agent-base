#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Integrity gate for template/ — a per-file hash manifest with a check.
//
// template/ is deliberately outside lint, Prettier and both tsconfigs: it is
// copied OUT of this repo, so the gates will not catch a mistake in it
// (CLAUDE.md, scope notes — "keep it honest by hand"). This gate closes the
// unintentional half of that gap without imposing anything on the files
// themselves: `template/template.manifest.json` records a sha256 per template
// file, and the check fails when the tree and the manifest disagree. An edit
// to template/ therefore has to be DELIBERATE — run `npm run template:fix` in
// the same change — while a stray edit, a bad merge, or an editor artefact
// surfaces as a named diff instead of shipping silently to the next scaffold.
//
// The manifest lives INSIDE template/ on purpose: the consumption test and
// real consumers scaffold by copying template/, so every scaffold carries the
// fingerprints of the template it came from. That recorded generation-time
// state is what makes a later three-way upgrade possible at all —
// scripts/upgrade-template.mjs compares it against the scaffold's on-disk
// files and the then-current template to tell "clean to overwrite" from
// "locally modified, needs a human" (the copier-style plan reviewed in
// bosun's docs/metaharness-feature-review.md §A1).
//
// Hashing normalises CRLF to LF so a Windows checkout and a Linux checkout of
// identical content agree; there is no .gitattributes in this repo, so
// checkout EOLs follow each machine's git config and must not count as drift.
//
//   --root <dir>      repo root (default: this script's parent directory).
//                     Lets the gate's own tests drive it against fixtures.
//   --template <dir>  template directory, repo-relative. Default: `template`.
//   --write           regenerate the manifest from the tree (the deliberate
//                     half; contrast check-context-pack.mjs's --write, which
//                     cannot finish the job — here the content IS derivable).
// ---------------------------------------------------------------------------
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const MANIFEST_NAME = 'template.manifest.json';

function flagValues(argv, name) {
  const out = [];
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === name && argv[i + 1]) out.push(argv[++i]);
  }
  return out;
}

/** Walk a template tree; POSIX-relative file paths, sorted, manifest excluded. */
export function listTemplateFiles(templateDir) {
  const out = [];
  const walk = (dir, rel) => {
    for (const entry of readdirSync(dir).sort()) {
      if (entry === 'node_modules' || entry === MANIFEST_NAME) continue;
      const abs = path.join(dir, entry);
      const entryRel = rel === '' ? entry : `${rel}/${entry}`;
      if (statSync(abs).isDirectory()) walk(abs, entryRel);
      else out.push(entryRel);
    }
  };
  walk(templateDir, '');
  return out.sort();
}

/** sha256 of a file with CRLF normalised to LF (checkout EOLs are not drift). */
export function hashTemplateFile(absPath) {
  const normalized = readFileSync(absPath).toString('binary').replaceAll('\r\n', '\n');
  return createHash('sha256').update(Buffer.from(normalized, 'binary')).digest('hex');
}

export function buildManifest(templateDir) {
  const files = {};
  for (const rel of listTemplateFiles(templateDir)) {
    files[rel] = hashTemplateFile(path.join(templateDir, rel));
  }
  return {
    schema: 1,
    note:
      'Per-file sha256 (CRLF-normalised) of the template this scaffold came from. ' +
      'Regenerated by `npm run template:fix` in agent-base; read by scripts/upgrade-template.mjs ' +
      'to three-way-merge template updates into a scaffolded repo. Do not edit by hand.',
    files,
  };
}

export function manifestJson(manifest) {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

// pathToFileURL, not string concatenation: a Windows path would produce an
// invalid file:// URL and silently make every invocation a no-op.
const isMain =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isMain) {
  const argv = process.argv.slice(2);
  const repoRoot = flagValues(argv, '--root').at(-1)
    ? path.resolve(flagValues(argv, '--root').at(-1))
    : path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const templateRel = flagValues(argv, '--template').at(-1) ?? 'template';
  const templateDir = path.join(repoRoot, templateRel);
  const manifestPath = path.join(templateDir, MANIFEST_NAME);

  if (!existsSync(templateDir)) {
    console.error(`check-template-manifest: no template directory at ${templateDir}`);
    process.exit(1);
  }

  const current = buildManifest(templateDir);

  if (argv.includes('--write')) {
    writeFileSync(manifestPath, manifestJson(current));
    console.log(
      `check-template-manifest: wrote ${templateRel}/${MANIFEST_NAME} (${Object.keys(current.files).length} files)`,
    );
    process.exit(0);
  }

  if (!existsSync(manifestPath)) {
    console.error(
      `check-template-manifest: ${templateRel}/${MANIFEST_NAME} is missing — run \`npm run template:fix\` and commit it`,
    );
    process.exit(1);
  }

  const recorded = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const problems = [];
  for (const [rel, hash] of Object.entries(current.files)) {
    const was = recorded.files?.[rel];
    if (was === undefined) problems.push(`added:   ${rel}`);
    else if (was !== hash) problems.push(`changed: ${rel}`);
  }
  for (const rel of Object.keys(recorded.files ?? {})) {
    if (!(rel in current.files)) problems.push(`removed: ${rel}`);
  }

  if (problems.length > 0) {
    console.error(`check-template-manifest: template/ and its manifest disagree:`);
    for (const p of problems.sort()) console.error(`  ${p}`);
    console.error(
      `A template edit must be deliberate: review the diff, then \`npm run template:fix\` in the same change.`,
    );
    process.exit(1);
  }
  console.log(
    `check-template-manifest: OK — ${Object.keys(current.files).length} files match ${templateRel}/${MANIFEST_NAME}`,
  );
}
